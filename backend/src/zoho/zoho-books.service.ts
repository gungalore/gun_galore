  // ─── Health check ────────────────────────────────────────────────

  /**
   * Lightweight probe for /admin/health. Pings the /organizations
   * endpoint to confirm auth + connectivity. Used by ZB-11.
   */
  async healthCheck(): Promise<{
    ok: boolean;
    enabled: boolean;
    detail?: string;
  }> {
    if (!this.enabled) {
      return { ok: true, enabled: false, detail: 'disabled by feature flag' };
    }
    if (!this.hasCredentials()) {
      return { ok: false, enabled: true, detail: 'missing credentials' };
    }
    try {
      type OrgsResp = { organizations?: Array<{ organization_id?: string }> };
      const resp = await this.request<OrgsResp>('GET', '/organizations');
      const orgIds = resp.organizations?.map((o) => o.organization_id) ?? [];
      if (!orgIds.includes(this.orgId)) {
        return {
          ok: false,
          enabled: true,
          detail: `org ${this.orgId} not visible to credentials`,
        };
      }
      return { ok: true, enabled: true, detail: 'auth + org access verified' };
    } catch (err) {
      return {
        ok: false,
        enabled: true,
        detail: (err as Error).message,
      };
    }
  }
