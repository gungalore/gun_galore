/**
 * THE SECOND FORM, FOR THE APPLICANTS WHO ACTUALLY NEED IT.
 *
 * ⚠️ CONDITIONAL, AND THAT IS THE WHOLE VALUE OF IT. A competency has no
 * lifespan of its own — s10(2) as amended ties it to the latest-dated licence
 * in its firearm category — so renewing an ordinary licence usually changes
 * nothing about it. But when the licence being renewed is the LAST one in that
 * category the competency expires on the same day, and s10A(1) requires the
 * competency renewal to be lodged TOGETHER WITH the licence renewal. Miss it
 * and the licence renewal can be accepted while the competency behind it
 * lapses, and the whole chain has to be rebuilt.
 *
 * ⚠️ SO IT MUST NOT APPEAR FOR EVERYONE. "You may also need a 517(g)" hedged
 * onto every renewal is noise, and noise is what trains somebody to skim the
 * one row that mattered. The finding is made in the Licence Centre, where the
 * member's own licences and certificates are — competencyRenewalNote owns the
 * rule and is silent unless it is sure of both halves — and arrives here as a
 * single answer. See COMPETENCY_RENEWS_KEY.
 *
 * ⚠️ THE ROW SAYS WHAT TO DO, NOT WHAT WE WORKED OUT. The member is not shown
 * arithmetic about their portfolio at a counter; they are shown the form to
 * bring. The Licence Centre's card carries the reasoning.
 */
const S24_COMPETENCY_RENEWAL: Omit<
  ChecklistItem,
  'done' | 'owner' | 'state' | 'closer'
> = {
  // ⚠️ NEVER RENAME. Hand-ticks are stored against this key.
  key: 's24_competency_517g',
  label: 'SAPS 517(g) competency renewal',
  note: 'Your competency in this category runs to this licence, so lodge its renewal together with this one. They are two separate forms with two separate fees, handed in on the same visit. Confirm the form number with your DFO.',
  verifyBeforeUse: true,
};

/**
 * The renewal rows, with the 517(g) in place if this applicant needs it.
 *
 * ⚠️ INSERTED BY ANCHOR KEY, NOT BY POSITION. It belongs directly after the
 * 90-day row — both are about what you lodge and when, while the
 * acknowledgement row is about what happens afterwards — and destructuring
 * S24_MUST_BRING by index would reorder itself silently the day a third row is
 * added there. If the anchor ever goes, the row still lands (at the end)
 * rather than disappearing: a slightly misplaced instruction beats a missing
 * one when the thing being missed is a lapsing competency.
 */
function s24Bring(
  answers: Record<string, string>,
): Omit<ChecklistItem, 'done' | 'owner' | 'state' | 'closer'>[] {
  // ⚠️ CASE-INSENSITIVE, DELIBERATELY. The registry's `yesno` fields store
  // 'Yes'; the value is written by another module and read by this one, and a
  // capital letter is not a thing anybody should be able to break a
  // counter-day instruction with. Anything that is not a yes is silence —
  // absent and "no" are the same answer here, because the finding is only
  // ever written when we are sure of it.
  const due = (answers[COMPETENCY_RENEWS_KEY] ?? '').trim().toLowerCase() === 'yes';
  if (!due) return [...S24_MUST_BRING];

  const out: Omit<ChecklistItem, 'done' | 'owner' | 'state' | 'closer'>[] = [];
  let placed = false;
  for (const row of S24_MUST_BRING) {
    out.push(row);
    if (row.key === 's24_ninety_days') {
      out.push(S24_COMPETENCY_RENEWAL);
      placed = true;
    }
  }
  if (!placed) out.push(S24_COMPETENCY_RENEWAL);
  return out;
}

/**
 * The one line telling the applicant who fills in the SAPS form, and how
 * much of it is theirs.
 *
 * ⚠️ NOT ALWAYS THE 271. A section 24 renewal is lodged on the SAPS 518(a) —
 * motivation-render.service.ts refuses to produce a 271 for one, by licence
 * type, and this product does not fill the 518(a) in at all (out of scope,
 * brief §9.4). A renewal's row must say so rather than describe a pre-filled
 * section this pack never produces.
 *
 * ⚠️ EVERY OTHER LICENCE TYPE'S 271 STOPPED BEING AN OPT-IN EXTRA ON
 * 2026-09-08 (brief §2.5, `MOTIVATION-INTAKE-PLAN.md` §1). We now complete
 * sections D, G and H unconditionally; section F is filled, ticked or left
 * blank by `firearm_source` alone (saps271.service.ts draws it,
 * saps271-map.ts decides it) — never by a choice made on this checklist. This
 * function only puts that outcome into plain words for the applicant in
 * front of them, and it must never claim more than the map actually draws:
 * see saps271-map.ts's own section-F comments before changing either route's
 * wording here.
 */
function saps271FormNote(
  licenceType: MotivationLicenceType,
  answers: Record<string, string>,
): string {
  if (licenceType === MotivationLicenceType.S24_RENEWAL) {
    return 'A renewal is lodged on the SAPS 518(a), not the 271 — get it from your DFO. Do NOT sign it beforehand — it must be signed in front of the DFO.';
  }

  const base =
    'We fill in your half of the SAPS 271 application form — sections D, G and H — from your answers and documents, and it is in your pack. Do NOT sign it beforehand — it must be signed in front of the DFO.';

  const source = (answers[FIREARM_SOURCE_KEY] ?? '').trim();
  if (source === SOURCE_DEALER) {
    // ⚠️ NAMES WHO FILLS THE REST, RATHER THAN LEAVING AN UNEXPLAINED GAP.
    // saps271-map.ts leaves section F blank on this route on purpose —
    // operator, 2026-08-28: "F. Type B and SAP 350 can be left alone, a
    // dealer needs to fill in those" — and the form itself carries the same
    // explanation as a `leftBlank` entry. Said again here so the applicant
    // knows before they get to the counter, not at it.
    return `${base} Section F is left blank for your dealer — they complete it along with their own SAPS 350(a); that half is theirs, not yours.`;
  }
  if (source === SOURCE_PRIVATE) {
    // ⚠️ NOT A PROMISE THAT F IS ALREADY DONE. It is filled once the seller
    // has actually completed and signed his consent (sectionF() in
    // motivation-seller-consent.service.ts returns nothing before that), so
    // this only says what the finished route looks like, not that it has
    // finished — the coverage panel's own 'F' row carries the live status.
    return `${base} Section F — the current owner's half — is filled from your seller's signed consent and printed as the page he signs.`;
  }
  // Unstated, or the estate route (which the 271 does not process at all —
  // see the "Type A and B only" ruling in saps271-map.ts): say only what is
  // certain, which is our own half.
  return base;
}

/**
 * Build the live checklist.
 *
 * `haveKinds` is what has actually been uploaded and `documentReady` whether the
 * motivation has passed the quality gate, so the "ours" items reflect real
 * state rather than intent.
 *
 * ⚠️ ONE ENTRY PER FILE, NOT A SET. The safe is one row holding several
 * photographs since 2026-08-23, so it is ticked by COUNT — and both callers
 * already pass a per-upload list. Deduplicating here would tick the safe row on
 * the first photograph, which is the failure the three separate kinds existed
 * to prevent.
 */
/**
 * Rows that only apply on some routes.
 *
 * ⚠️ THE LIST WENT TO EVERY APPLICANT WHATEVER THEY ANSWERED. MO000071 was a
 * private-owner purchase and its take-to-the-station pages told the applicant
 * to bring "the dealer's tax invoice for the firearm" — there is no dealer and
 * there will be no tax invoice, so the list sent somebody to a counter looking
 * for a document that does not exist. Every row here is a row that is right
 * for one route and wrong for another; a row with no entry applies to
 * everybody, which is the safe default for anything added later.
 */
const BRING_ONLY_WHEN: Record<
  string,
  (answers: Record<string, string>) => boolean
> = {
  /**
   * A tax invoice comes from a dealer. On a private sale the proof of purchase
   * is the seller's own paperwork and the signed consent, which are elsewhere
   * in the pack; on an inherited firearm there is no purchase at all.
   */
  tax_invoice: (a) =>
    !/private|inherit|estate|deceased/i.test(a[FIREARM_SOURCE_KEY] ?? ''),
  /**
   * ⚠️ AND CHARACTER REFERENCES WERE OFFERED WITH NOWHERE TO PUT THEM. The row
   * says "if you have them" while the sheet has no character-reference slot,
   * so an applicant who took the advice arrived holding a letter the pack
   * could not carry. CHARACTER_REFERENCE exists as an upload kind and the
   * witness flow collects signed statements — the row belongs where those are
   * gathered, and until it is offered there it is not offered at all.
   */
  character_references: () => false,
};

function bringApplies(key: string, answers: Record<string, string>): boolean {
  const rule = BRING_ONLY_WHEN[key];
  return rule ? rule(answers) : true;
}

export function buildChecklist(
  licenceType: MotivationLicenceType,
  haveKinds: MotivationUploadKind[],
  documentReady = false,
  context: ChecklistContext = {},
): ChecklistProgress {
  const waitingOn = context.waitingOn ?? {};

  /**
   * The three states, derived from `done` and who we are waiting on — never
   * decided independently, so `state` cannot drift from `done`.
   */
  const stateOf = (key: string, done: boolean): ChecklistState =>
    done ? 'done' : waitingOn[key] ? 'waiting-on-someone' : 'not-started';

  const annexures = buildAnnexures(haveKinds);
  const counts = new Map<MotivationUploadKind, number>();
  for (const k of haveKinds) counts.set(k, (counts.get(k) ?? 0) + 1);
  const enough = (kind: MotivationUploadKind) =>
    (counts.get(kind) ?? 0) >= (kind === 'SAFE_PHOTOGRAPHS' ? SAFE_PHOTO_MIN : 1);
  const byKind = new Map(annexures.map((a) => [a.kind, a]));

  const ours: ChecklistItem[] = [
    {
      key: 'motivation',
      label: 'Your motivation',
      owner: 'us',
      done: documentReady,
      state: stateOf('motivation', documentReady),
      closer: documentReady
        ? 'We have written this from your answers.'
        : 'We write this for you, once the questions are answered.',
      note: documentReady ? undefined : 'Finish the questions and we will prepare it.',
    },
    {
      key: 'paja',
      label: 'Request for prior notice before refusal (PAJA)',
      owner: 'us',
      done: documentReady,
      state: stateOf('paja', documentReady),
      closer: 'We prepare this and it is lodged with the application.',
      note: 'Lodged together with the application.',
    },
  ];

  // Everything recommended for this licence type, done or not — so a missing
  // item is visible rather than silently absent.
  for (const kind of RECOMMENDED[licenceType]) {
    const entry = byKind.get(kind);
    const key = `upload_${kind.toLowerCase()}`;
    const have = enough(kind);
    const item: ChecklistItem = {
      key,
      label: UPLOAD_KIND_LABELS[kind],
      owner: 'us',
      done: have,
      state: stateOf(key, have),
      // A row somebody else is finishing says so, in their words. Otherwise
      // it names the two doors — and only ever those two.
      closer:
        waitingOn[key] ??
        (have
          ? 'We hold this. Send another and it replaces it.'
          : 'Scan it with your phone, or upload it.'),
      // ⚠️ OFFERED EVEN WHEN THE ROW IS DONE. A member who photographed the
      // wrong page needs a way to replace it without deleting first.
      captureRoutes: ['qr', 'upload'],
      annexure: entry?.letter,
    };
    // ⚠️ THE ROW COLLAPSED; THE INSTRUCTION MUST NOT. One line now takes every
    // photograph of the safe, so this note is the only place a member is told
    // which pictures to take.
    //
    // ⚠️ THE THIRD SHOT IS THE WALL, NOT THE DOOR. Operator, 2026-08-23:
    // "no bolts needs be in the door. They need to be roll bolts in the wall.
    // Get rid of the bolts in the door." We used to ask for the safe fully
    // open so the locking bolts in the door were visible, and to treat the
    // anchoring as an optional fourth. That is backwards: a photograph of the
    // door proves the lock works on a box that can be carried out of the
    // house, and it is the bolts into the WALL that a DFO is actually looking
    // for. The club checklist a real S16 pack was submitted with asks for
    // exactly three, and its third is "bolts that hold the safe against the
    // wall".
    if (kind === 'SAFE_PHOTOGRAPHS') {
      item.note =
        'Add them all on this one line: the safe closed with the key out, half open with the key in the door, and the roll bolts that hold the safe to the wall. A DFO looks for all three.';
    }
    if (kind === 'INCIDENT_REPORT') {
      item.note =
        'Any SAPS case number or armed-response report from an incident that affected you. Far stronger than general crime figures.';
    }
    ours.push(item);
  }

  // ⚠️ THE COMMON LIST WAS THE WHOLE LIST for every licence type, so a
  // section 16 applicant walked to the counter with no mention of the three
  // association documents their application rests on.
  /**
   * ⚠️ ROUTE-AWARE AND SECTION-AWARE, WHICH IS THE WHOLE POINT OF THE
   * SHEET. MOTIVATION-GUIDE-BOOK Part 10.2 and 10.3. The rows that get people
   * turned away are almost never on the common list — they are the dealer's
   * stamped 350(a), the seller's licence copied on one side only, the
   * association endorsement that was never issued because an activity report
   * was outstanding. Each of those belongs to exactly one route or one
   * section, and printed on everybody's sheet they are noise that trains a
   * reader to skim.
   */
  const bring = [
    ...APPLICANT_MUST_BRING,
    ...(ROUTE_MUST_BRING[
      (context.answers?.[FIREARM_SOURCE_KEY] ?? '').trim()
    ] ?? []),
    ...(SECTION_MUST_BRING[licenceType] ?? []),
    ...(licenceType === 'S16_DEDICATED_HUNTER' ||
    licenceType === 'S16_DEDICATED_SPORT'
      ? S16_MUST_BRING
      : []),
    ...(licenceType === 'S24_RENEWAL' ? s24Bring(context.answers ?? {}) : []),
  ].filter((i) => bringApplies(i.key, context.answers ?? {}));
  const theirs: ChecklistItem[] = bring.map((i) => ({
    ...i,
    owner: 'applicant' as const,
    done: false,
    state: stateOf(i.key, false),
    // ⚠️ ONE UNIFORM SENTENCE, AND NO captureRoutes. These are certified
    // copies, passport photographs, fingerprints and a fee — things we do not
    // hold and must never imply we could take an upload of. The section intro
    // carries the regulation detail; this line only answers "so what do I do".
    closer: waitingOn[i.key] ?? 'You bring this with you to the counter.',
    // ⚠️ THE ONE ROW WHOSE NOTE DEPENDS ON MORE THAN ITSELF. Which form this
    // even is, and who fills which half of it, turns on the licence type and
    // `firearm_source` — see saps271FormNote. `context.answers ?? {}` rather
    // than skipping the override when answers are absent: a caller with no
    // answers to hand should see the honest "our half, form TBC by route"
    // sentence, not the stale placeholder above.
    ...(i.key === 'saps_form'
      ? { note: saps271FormNote(licenceType, context.answers ?? {}) }
      : {}),
  }));

  const warnings = applicationWarnings(licenceType, context.answers ?? {});
  const oursDone = ours.filter((i) => i.done).length;

  return {
    sections: [
      {
        key: 'ours',
        title: 'Your pack',
        intro:
          'We prepare these, and you upload the supporting documents here. Everything stays digital until you print.',
        items: ours,
      },
      {
        key: 'theirs',
        title: 'Take these to your Designated Firearms Officer',
        // ⚠️ WHY THIS LIST EXISTS, in one sentence the applicant can act on.
        // Regulation 13(10): the DFO does not have to accept an incomplete
        // application, and the acknowledgement is withheld until the pack IS
        // complete. A pack checked before you travel is the difference between
        // walking out with a receipt and walking out with nothing.
        // ⚠️ WHICH DFO, AND WHO HANDS IT IN. Neither was stated anywhere.
        // Reg 13(4)(a): "An application must, unless otherwise specifically
        // stated, be submitted by the applicant in person to the relevant
        // Designated Firearms Officer", and reg 1(xix) defines "relevant" as
        // the officer for the area where the applicant ordinarily resides.
        // Reg 13(9)(a) and 13(10) independently need the applicant in the
        // flesh — the DFO takes their fingerprints at the counter and checks
        // them against their identity before any acknowledgement issues,
        // which is the sharp answer to "can my wife drop it off".
        //
        // Two drafting cautions kept in the wording: reg 1(xix) has a
        // business limb, and reg 13(4)(a) opens "unless otherwise
        // specifically stated" — so this must not be phrased as admitting no
        // exception ever.
        intro:
          'The application goes to the Designated Firearms Officer for the area where you ordinarily live — not to whichever station is nearest or quietest — and you normally have to hand it in yourself. Your spouse, your dealer or a friend cannot lodge it for you: the DFO takes your fingerprints at the counter and checks them against your identity before anything is accepted. A DFO does not have to accept an incomplete application and will not issue the acknowledgement until it is complete, so it is worth checking every line before you travel. Requirements differ between stations and this list is not exhaustive: confirm it with your own DFO.',
        items: theirs,
      },
    ],
    warnings,
    oursDone,
    oursTotal: ours.length,
    theirsTotal: theirs.length,
  };
}
