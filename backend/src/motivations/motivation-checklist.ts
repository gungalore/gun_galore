/**
 * Build the live checklist.
 *
 * `haveKinds` is what has actually been uploaded and `documentReady` whether the
 * motivation has passed the quality gate, so the "ours" items reflect real
 * state rather than intent.
 */
export function buildChecklist(
  licenceType: MotivationLicenceType,
  haveKinds: MotivationUploadKind[],
  documentReady = false,
): ChecklistProgress {
  const annexures = buildAnnexures(haveKinds);
  const have = new Set(haveKinds);
  const byKind = new Map(annexures.map((a) => [a.kind, a]));

  const ours: ChecklistItem[] = [
    {
      key: 'motivation',
      label: 'Your motivation',
      owner: 'us',
      done: documentReady,
      note: documentReady ? undefined : 'Finish the questions and we will prepare it.',
    },
    {
      key: 'paja',
      label: 'Request for prior notice before refusal (PAJA)',
      owner: 'us',
      done: documentReady,
      note: 'Lodged together with the application.',
    },
  ];

  // Everything recommended for this licence type, done or not — so a missing
  // item is visible rather than silently absent.
  for (const kind of RECOMMENDED[licenceType]) {
    const entry = byKind.get(kind);
    const item: ChecklistItem = {
      key: `upload_${kind.toLowerCase()}`,
      label: UPLOAD_KIND_LABELS[kind],
      owner: 'us',
      done: have.has(kind),
      annexure: entry?.letter,
    };
    if (kind === 'SAFE_PHOTO_CLOSED') {
      item.note =
        'Three photographs of the safe, each its own line below — a DFO looks for all three.';
    }
    if (kind === 'INCIDENT_REPORT') {
      item.note =
        'Any SAPS case number or armed-response report from an incident that affected you. Far stronger than general crime figures.';
    }
    ours.push(item);
  }

  const theirs: ChecklistItem[] = APPLICANT_MUST_BRING.map((i) => ({
    ...i,
    owner: 'applicant' as const,
    done: false,
  }));

  const oursDone = ours.filter((i) => i.done).length;

  return {
    sections: [
      {
        key: 'ours',
        title: 'Your pack',
        intro:
          'We prepare these, and you upload the supporting documents here. Everything stays digital until you print.',
        items: ours,
      },
      {
        key: 'theirs',
        title: 'Take these to the police station',
        // ⚠️ WHY THIS LIST EXISTS, in one sentence the applicant can act on.
        // Regulation 13(10): the DFO does not have to accept an incomplete
        // application, and the acknowledgement is withheld until the pack IS
        // complete. A pack checked before you travel is the difference between
        // walking out with a receipt and walking out with nothing.
        intro:
          'We do not hold these — you bring them yourself. A DFO does not have to accept an incomplete application, and will not issue the acknowledgement until it is complete, so it is worth checking every line before you travel. Requirements differ between stations and this list is not exhaustive: confirm it with your own DFO.',
        items: theirs,
      },
    ],
    oursDone,
    oursTotal: ours.length,
    theirsTotal: theirs.length,
  };
}
