// ────────────────────────────────────────────────────────────────────
// THE SUBMISSION CHECKLIST — a LIVE, TICKABLE SURFACE, not a PDF page.
//
// Operator, 2026-08-18: "The tick boxes must be on the platform and PWA, not a
// PDF document. The whole point of this is to have it all digital until the
// document is ready to be printed."
//
// So this module is DATA. It reports what is done, what is outstanding, and
// what the applicant has to fetch themselves; the platform and the PWA render
// it as a progress list they tick as they go, and it stays live right up to the
// moment they print. Only the ANNEXURE INDEX goes into the printed document —
// a reviewer holding the paper needs to find what the body cross-references.
//
// THE CONTENT IS THE OPERATOR'S OWN LIST ("Neem saam na SAP"), not a generic
// one I invented. It is materially better because it comes from someone who has
// actually lodged these applications: it names the THREE specific safe
// photographs a DFO wants, the fee per firearm, and the warning not to sign the
// SAPS forms in advance. That last one is the kind of detail that costs a
// wasted trip to the station if you get it wrong.
//
// TWO ITEM CLASSES, and the distinction is the whole design:
//   OURS   — generated by us or uploaded by the applicant. We know the state,
//            so these tick themselves.
//   THEIRS — SAPS forms, certified copies, passport photographs, the fee. We
//            do NOT hold these and must never imply we do. They stay tickable
//            by hand, and the list says plainly that it is not exhaustive and
//            that requirements differ by station.
//
// ⚠️ VERIFY BEFORE GO-LIVE: the fee and the SAPS form number are the two things
// most likely to be quietly out of date. They are marked `verifyBeforeUse`.
// ────────────────────────────────────────────────────────────────────

/** Who is responsible for producing the item. */
export type ChecklistOwner = 'us' | 'applicant';

/**
 * Where a row stands, in three states rather than two.
 *
 * ⚠️ 'waiting-on-someone' MUST NOT COLLAPSE INTO 'not-started'. A witness who
 * has been invited and a witness who has never been asked look identical
 * through a boolean, and they are not remotely the same thing: the applicant
 * has already done their part on the first one and has nothing left to do but
 * wait. Telling them it is "not started" is telling them to redo work.
 */
export type ChecklistState = 'done' | 'waiting-on-someone' | 'not-started';

/**
 * The only two ways evidence gets onto a row. Anywhere. On any surface.
 *
 * Operator, 2026-08-28: "we do not use webcams for upload. Only Open scanner
 * with QR, Upload." A third member is not a feature request, it is a bug.
 */
export type CaptureRoute = 'qr' | 'upload';

/**
 * What the pure builder cannot know by itself.
 *
 * ⚠️ THE THIRD-PARTY STATUS HAS TO BE INJECTED, and that is deliberate.
 * buildChecklist is pure — no Prisma, no clock — and whether a seller has
 * opened his link lives in two services. Passing it in keeps the builder
 * testable and keeps every caller honest, because a caller that forgets it
 * gets 'not-started' rather than something plausible and wrong.
 */
export interface ChecklistContext {
  /**
   * Item key → the one sentence to show for a row we are waiting on somebody
   * else for. The sentence names WHO, because "waiting" without a name is
   * indistinguishable from stuck.
   */
  waitingOn?: Record<string, string>;
  /**
   * The application's answers, for the handful of rows that only apply to
   * some applicants.
   *
   * ⚠️ READ, NEVER RENDERED. Nothing here puts an answer's VALUE on the
   * screen: these are somebody's personal details and this list is printed,
   * shared and screenshotted. It is read to decide whether a row exists at
   * all — see COMPETENCY_RENEWS_KEY, which the Licence Centre writes when it
   * can see that renewing this licence also expires the competency behind it.
   *
   * Optional, and an omitted map means "no conditional rows". A caller that
   * has not got the answers to hand shows the unconditional list rather than
   * guessing — the failure mode is a row missing from a list that says at the
   * top it is not exhaustive, not a wrong instruction about a form.
   */
  answers?: Record<string, string>;
}

export interface ChecklistItem {
  /**
   * Stable key so the UI can persist a hand-tick against it.
   *
   * ⚠️ NEVER RENAME ONE. The frontend stores hand-ticks under this key; a
   * rename silently orphans every tick a member has already made, and they
   * see work they did come back undone.
   */
  key: string;
  label: string;
  owner: ChecklistOwner;
  /**
   * True only for `owner: 'us'` items we can actually confirm.
   *
   * ⚠️ ITS MEANING IS UNCHANGED BY `state` BELOW, and must stay that way.
   * `state === 'done'` implies `done`, but not the reverse. Folding a
   * third-party signal into `done` would move `oursDone`/`oursTotal` — the
   * progress ring an existing screen already renders — with no type error to
   * catch it.
   */
  done: boolean;
  /** Richer read of the same row. Derived; never contradicts `done`. */
  state: ChecklistState;
  /**
   * One sentence: who closes this row, and how.
   *
   * ⚠️ DERIVED, NOT AUTHORED PER ROW. The 'theirs' copy in this module
   * carries live regulation citations and operator-verified specifics, some
   * of it flagged verifyBeforeUse. Writing nineteen fresh bespoke sentences
   * beside it is how a legally reviewed list acquires an unreviewed
   * paraphrase that contradicts it. So this is computed from what the row IS,
   * and the section intro keeps carrying the detail.
   */
  closer: string;
  /** Offered when the row expands. Omitted where nothing can be captured. */
  captureRoutes?: CaptureRoute[];
  /** Annexure letter, where this is one of ours. */
  annexure?: string;
  /** Shown smaller under the label. */
  note?: string;
  // subItems lived here: sub-points hanging off one row, and the three safe
  // photographs were the only thing that ever used them. They went with the
  // collapse on 2026-08-23 — the safe is one row now and what the member needs
  // to be told is the `note` above, which names every shot. Nothing wrote the
  // field afterwards and nothing rendered it, so it was a hook advertising a
  // feature that no longer existed. It comes back with sub-items, if they do.
  /** Operator/attorney must confirm this is current before go-live. */
  verifyBeforeUse?: true;
}

export interface ChecklistSection {
  key: string;
  title: string;
  intro?: string;
  items: ChecklistItem[];
}

export interface ChecklistProgress {
  sections: ChecklistSection[];
  /** Items we own that are done, over items we own. Drives the progress ring. */
  oursDone: number;
  oursTotal: number;
  /** Count the applicant still has to gather themselves. */
  theirsTotal: number;
  /**
   * Where the Act is stricter than what the CFR sometimes accepts.
   *
   * ⚠️ ON THE APPLICANT'S OWN PAGE, NEVER IN THE MOTIVATION. See
   * motivation-warnings.ts: a document that argues against its own application
   * hands the Registrar their refusal in the applicant's own words. These
   * print on the sheet that is removed at the counter.
   */
  warnings: ApplicationWarning[];
}

