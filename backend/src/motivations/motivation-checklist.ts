/**
 * Every upload kind, mapped to the annexure entry that letters it.
 *
 * ⚠️ A GROUPED KIND IS NOT ITS OWN ENTRY, AND LOOKING IT UP DIRECTLY RETURNS
 * NOTHING. buildAnnexures collapses the safe kinds onto one letter and the two
 * association documents onto another, so the returned list is keyed by each
 * group's REPRESENTATIVE kind. A caller that does
 * `entries.find(e => e.kind === upload.kind)` therefore finds the group's
 * representative and misses every other member of it.
 *
 * ⚠️ STILL NEEDED AFTER 2026-08-23. The safe is one kind now, but the
 * association group is not, and neither are the retired safe kinds a member's
 * older application still carries.
 *
 * That is not hypothetical: it shipped. A live pack printed
 * "Annexure ? — SAFE_PHOTO_AJAR" and "Annexure ? — GOOD_STANDING_LETTER" as
 * captions on the reprinted copies, with the raw enum name showing, because
 * the map was built from the entry list and read by member kind.
 *
 * Use this rather than building a map by hand.
 */
export function annexureByKind(
  entries: AnnexureEntry[],
): Map<MotivationUploadKind, AnnexureEntry> {
  const out = new Map<MotivationUploadKind, AnnexureEntry>();
  for (const entry of entries) {
    if (entry.generated) continue;
    const kind = entry.kind as MotivationUploadKind;
    const group = LETTER_GROUPS[kind];
    if (!group) {
      out.set(kind, entry);
      continue;
    }
    // Every member of the group answers to the group's entry.
    for (const k of Object.keys(LETTER_GROUPS) as MotivationUploadKind[]) {
      if (LETTER_GROUPS[k]?.id === group.id) out.set(k, entry);
    }
  }
  return out;
}

export interface AnnexureEntry {
  letter: string;
  kind: AnnexureKind;
  label: string;
  count: number;
  /** Whether this annexure needs a commissioner's stamp, and how firmly. */
  certification: CertificationLevel;
  /** True for documents we produce rather than ones the applicant uploaded. */
  generated?: true;
}

/**
 * Assign annexure letters to what was actually uploaded.
 *
 * Letters go to KINDS, not files, so two copies of one ID share a letter — and
 * since 2026-08-23 so do every photograph of the safe, which is one kind. The
 * copies stay individually citable through the "(2 of 4)" captions
 * motivation-annexure-layout.ts prints above each one.
 */
export function buildAnnexures(
  kinds: MotivationUploadKind[],
  /**
   * Documents we generate that are ready to go into this pack.
   *
   * Passed in rather than assumed, because a pack whose motivation has not
   * been written yet has no prior-notice request either — and lettering a
   * document that does not exist would put a gap in the index a reviewer
   * would go looking for.
   */
  generated: GeneratedAnnexureId[] = [],
): AnnexureEntry[] {
  const counts = new Map<MotivationUploadKind, number>();
  for (const k of kinds) counts.set(k, (counts.get(k) ?? 0) + 1);
  const made = new Set(generated);

  const out: AnnexureEntry[] = [];
  let i = 0;
  /** Letters already spent, so a grouped kind reuses its group's letter. */
  const groupLetter = new Map<string, string>();

  for (const kind of ANNEXURE_ORDER) {
    const isGenerated = kind in GENERATED_ANNEXURE_LABELS;
    if (isGenerated) {
      if (!made.has(kind as GeneratedAnnexureId)) continue;
      out.push({
        letter: String.fromCharCode(65 + i),
        kind,
        label: GENERATED_ANNEXURE_LABELS[kind as GeneratedAnnexureId],
        count: 1,
        certification: CERTIFICATION[kind] ?? 'none',
        generated: true,
      });
      i++;
      continue;
    }
    const uploadKind = kind as MotivationUploadKind;
    const count = counts.get(uploadKind);
    if (!count) continue;

    const group = LETTER_GROUPS[uploadKind];
    if (group) {
      const existing = groupLetter.get(group.id);
      if (existing) {
        // Same letter, one more document under it. The entry's count is what
        // drives "(2 of 4)" on the printed copy, so it has to accumulate.
        const row = out.find((e) => e.letter === existing);
        if (row) row.count += count;
        continue;
      }
      const letter = String.fromCharCode(65 + i);
      groupLetter.set(group.id, letter);
      out.push({
        letter,
        kind: uploadKind,
        label: group.label,
        count,
        certification: CERTIFICATION[uploadKind] ?? 'none',
      });
      i++;
      continue;
    }

    out.push({
      letter: String.fromCharCode(65 + i),
      kind: uploadKind,
      label: UPLOAD_KIND_LABELS[uploadKind],
      count,
      certification: CERTIFICATION[uploadKind] ?? 'none',
    });
    i++;
  }
  return out;
}

