// ────────────────────────────────────────────────────────────────────
// THE SUBMISSION CHECKLIST — a LIVE, TICKABLE SURFACE, not a PDF page.
//
// Operator, 2026-08-18: "The tick boxes must be on the platform and PWA, not a
// PDF document. The whole point of this is to have it all digital until the
// document is ready to be printed."
//
// So this module is DATA. It reports what is done, what is outstanding, and
// what the applicant has to fetch themselves; the platform and the PWA render
// it as a progress list they tick as they go, and it stays live right up to the
// moment they print. Only the ANNEXURE INDEX goes into the printed document —
// a reviewer holding the paper needs to find what the body cross-references.
//
// THE CONTENT IS THE OPERATOR'S OWN LIST ("Neem saam na SAP"), not a generic
// one I invented. It is materially better because it comes from someone who has
// actually lodged these applications: it names the THREE specific safe
// photographs a DFO wants, the fee per firearm, and the warning not to sign the
// SAPS forms in advance. That last one is the kind of detail that costs a
// wasted trip to the station if you get it wrong.
//
// TWO ITEM CLASSES, and the distinction is the whole design:
//   OURS   — generated by us or uploaded by the applicant. We know the state,
//            so these tick themselves.
//   THEIRS — SAPS forms, certified copies, passport photographs, the fee. We
//            do NOT hold these and must never imply we do. They stay tickable
//            by hand, and the list says plainly that it is not exhaustive and
//            that requirements differ by station.
//
// ⚠️ VERIFY BEFORE GO-LIVE: the fee and the SAPS form number are the two things
// most likely to be quietly out of date. They are marked `verifyBeforeUse`.
// ────────────────────────────────────────────────────────────────────

/** Who is responsible for producing the item. */
export type ChecklistOwner = 'us' | 'applicant';

export interface ChecklistItem {
  /** Stable key so the UI can persist a hand-tick against it. */
  key: string;
  label: string;
  owner: ChecklistOwner;
  /** True only for `owner: 'us'` items we can actually confirm. */
  done: boolean;
  /** Annexure letter, where this is one of ours. */
  annexure?: string;
  /** Shown smaller under the label. */
  note?: string;
  /** Sub-points — e.g. the three safe photographs. */
  subItems?: { key: string; label: string; done?: boolean }[];
  /** Operator/attorney must confirm this is current before go-live. */
  verifyBeforeUse?: true;
}

export interface ChecklistSection {
  key: string;
  title: string;
  intro?: string;
  items: ChecklistItem[];
}

export interface ChecklistProgress {
  sections: ChecklistSection[];
  /** Items we own that are done, over items we own. Drives the progress ring. */
  oursDone: number;
  oursTotal: number;
  /** Count the applicant still has to gather themselves. */
  theirsTotal: number;
}

