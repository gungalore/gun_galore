// Generate frontend/lib/post-vocab-cartridges.ts from the CIP reference CSV.
//
//   cd backend && npx ts-node --transpile-only scripts/build-post-vocab-cartridges.ts
//
// The community composer's "Calibre / Cartridge" field wants a long list with
// proper display names. The Bench list is load-bearing only (~165) and its name
// is the European printed form ("6,5 Creedmoor"); the CIP file has the proper
// spelled name for every cartridge. Output is committed; the script is kept so
// a refreshed CSV can be regenerated.

import * as fs from 'node:fs';
import * as path from 'node:path';

const CSV = path.join(__dirname, '..', 'prisma', 'seed-data', 'grt-caliber.csv');
const OUT = path.join(__dirname, '..', '..', 'frontend', 'lib', 'post-vocab-cartridges.ts');

function slug(s: string): string {
  return s
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

/** Minimal CSV line parser: handles quoted fields with commas and "" escapes. */
function parseLine(line: string): string[] {
  const out: string[] = [];
  let cur = '';
  let quoted = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (quoted) {
      if (ch === '"') {
        if (line[i + 1] === '"') {
          cur += '"';
          i++;
        } else {
          quoted = false;
        }
      } else {
        cur += ch;
      }
    } else if (ch === '"') {
      quoted = true;
    } else if (ch === ',') {
      out.push(cur);
      cur = '';
    } else {
      cur += ch;
    }
  }
  out.push(cur);
  return out;
}

const raw = fs.readFileSync(CSV, 'utf8').split(/\r?\n/);
const header = parseLine(raw[0]);
const iName = header.indexOf('cipname');
const iAlt = header.indexOf('altname');
if (iName < 0) throw new Error('cipname column not found in ' + CSV);

const byValue = new Map<string, { label: string; aliases: string[] }>();
for (let i = 1; i < raw.length; i++) {
  const line = raw[i];
  if (!line.trim()) continue;
  const cols = parseLine(line);
  const name = (cols[iName] ?? '').trim();
  if (!name) continue;
  const value = slug(name);
  if (!value) continue;
  const alt = iAlt >= 0 ? (cols[iAlt] ?? '').trim() : '';
  const existing = byValue.get(value);
  if (existing) {
    if (alt && alt !== name && !existing.aliases.includes(alt)) existing.aliases.push(alt);
  } else {
    byValue.set(value, { label: name, aliases: alt && alt !== name ? [alt] : [] });
  }
}

const rows = [...byValue.entries()].sort((a, b) => a[1].label.localeCompare(b[1].label));
const body = rows
  .map(([value, x]) => {
    const aliases = x.aliases.length ? `, aliases: ${JSON.stringify(x.aliases)}` : '';
    return `  { value: ${JSON.stringify(value)}, label: ${JSON.stringify(x.label)}${aliases} },`;
  })
  .join('\n');

const out = `// GENERATED by backend/scripts/build-post-vocab-cartridges.ts — do not edit by hand.
// Source: backend/prisma/seed-data/grt-caliber.csv (CIP reference).
// Regenerate: cd backend && npx ts-node --transpile-only scripts/build-post-vocab-cartridges.ts
import type { VocabEntry } from './post-vocab';

export const CARTRIDGES: readonly VocabEntry[] = [
${body}
];
`;
fs.writeFileSync(OUT, out, 'utf8');
console.log(`wrote ${rows.length} cartridges -> ${OUT}`);
